import AppKit
import Combine

/// 剪贴板历史。纯本地、零权限、**只在内存**（退出即清，不落盘）。
///
/// 采集靠轮询 `NSPasteboard.changeCount`（0.5s），比事件监听省事且不需要辅助功能。
/// 隐私：识别密码管理器约定的私有类型后直接丢弃，不进历史。
final class ClipboardService: ObservableObject {
    static let shared = ClipboardService()

    enum Kind { case text, image, files }

    struct Item: Identifiable {
        let id = UUID()
        let kind: Kind
        let preview: String
        let text: String?
        let image: NSImage?
        let urls: [URL]
        let date: Date
        let signature: String
    }

    @Published private(set) var items: [Item] = []
    @Published private(set) var justCopied: UUID?
    /// 固定条目：不被条数上限挤掉，「清空」时保留。只在内存里，退出即清。
    @Published private(set) var pinned: Set<UUID> = []

    private var timer: Timer?
    private var lastChangeCount = -1
    /// 我们自己写回剪贴板时产生的那次变化，不要记进历史
    private var suppressedChangeCount = -1

    private let maxItems = 20
    private let maxImages = 5

    /// 密码管理器 / 系统约定的「别记录」类型
    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.1password.1password"
    ]

    private init() {}

    func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    // MARK: - 采集

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        guard lastChangeCount != suppressedChangeCount else { return }
        capture(pb)
    }

    private func capture(_ pb: NSPasteboard) {
        let types = Set(pb.types?.map(\.rawValue) ?? [])
        guard types.isDisjoint(with: Self.privateTypes) else { return }

        // 文件优先：拖/拷贝文件时通常同时带 string，先判 URL 才不会退化成路径文本
        if let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let sig = "f:" + urls.map(\.path).joined(separator: "|")
            insert(Item(kind: .files,
                        preview: urls.count == 1 ? urls[0].lastPathComponent : String(format: L("%d 个文件"), urls.count),
                        text: nil, image: nil, urls: urls, date: Date(), signature: sig))
            return
        }

        if let s = pb.string(forType: .string) {
            let trimmed = s.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { return }
            let preview = trimmed
                .replacingOccurrences(of: "\n", with: " ")
                .replacingOccurrences(of: "\t", with: " ")
            insert(Item(kind: .text,
                        preview: String(preview.prefix(180)),
                        text: s, image: nil, urls: [], date: Date(), signature: "t:" + s))
            return
        }

        if let img = NSImage(pasteboard: pb) {
            let w = Int(img.size.width), h = Int(img.size.height)
            let bytes = img.tiffRepresentation?.count ?? 0
            insert(Item(kind: .image,
                        preview: String(format: L("图片 %d×%d"), w, h),
                        text: nil, image: img, urls: [], date: Date(),
                        signature: "i:\(w)x\(h):\(bytes)"))
        }
    }

    private func insert(_ item: Item) {
        if items.first?.signature == item.signature { return }   // 连续重复不重复记
        items.insert(item, at: 0)

        // 图片单独限额：一张截图几 MB，不能和文本一样堆 20 份。
        // 固定项不参与淘汰，否则「固定」会被下一次复制顶掉。
        var seenImages = 0
        items = items.filter { it in
            guard it.kind == .image, !pinned.contains(it.id) else { return true }
            seenImages += 1
            return seenImages <= maxImages
        }
        if items.count > maxItems {
            var overflow = items.count - maxItems
            items = items.filter { it in
                guard overflow > 0, !pinned.contains(it.id) else { return true }
                overflow -= 1
                return false
            }
        }
    }

    // MARK: - 写回

    func copy(_ item: Item) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text:
            if let t = item.text { pb.setString(t, forType: .string) }
        case .image:
            if let i = item.image { pb.writeObjects([i]) }
        case .files:
            pb.writeObjects(item.urls as [NSURL])
        }
        suppressedChangeCount = pb.changeCount
        lastChangeCount = pb.changeCount

        justCopied = item.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            if self?.justCopied == item.id { self?.justCopied = nil }
        }
    }

    /// 按 id 复制。插件只拿到历史条目的 id，图片/文件不需要传数据。
    func copy(id: UUID) {
        guard let item = items.first(where: { $0.id == id }) else { return }
        copy(item)
    }

    func isPinned(_ id: UUID) -> Bool { pinned.contains(id) }

    func setPinned(_ id: UUID, _ on: Bool) {
        guard items.contains(where: { $0.id == id }) else { return }
        if on { pinned.insert(id) } else { pinned.remove(id) }
    }

    func remove(_ id: UUID) {
        items.removeAll { $0.id == id }
        pinned.remove(id)
    }

    /// 清空未固定条目；固定的保留。
    func clear() {
        items.removeAll { !pinned.contains($0.id) }
    }

    // MARK: - 展示辅助

    func ageText(_ date: Date) -> String {
        let s = Date().timeIntervalSince(date)
        if s < 60 { return L("刚刚") }
        if s < 3600 { return String(format: L("%d 分"), Int(s / 60)) }
        if s < 86400 { return String(format: L("%d 时"), Int(s / 3600)) }
        return String(format: L("%d 天"), Int(s / 86400))
    }
}
